# Creates .env in the repository root with freshly generated secrets.
# Refuses to overwrite an existing .env (delete it yourself if you really want new secrets:
# a new POSTGRES_PASSWORD will not match an existing database volume).
$ErrorActionPreference = "Stop"
$Root = Split-Path -Parent $PSScriptRoot
$EnvFile = Join-Path $Root ".env"
if (Test-Path -LiteralPath $EnvFile) { Write-Host ".env already exists; leaving it unchanged." -ForegroundColor Yellow; exit 0 }

function New-Secret([int]$Bytes) {
    $buffer = New-Object byte[] $Bytes
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($buffer)
    -join ($buffer | ForEach-Object { $_.ToString("x2") })
}

$Lines = @(
    "# Generated by scripts/init-env.ps1 on $(Get-Date -Format s). Never commit this file.",
    "INDUSMIND_ENV=development",
    "SECRET_KEY=$(New-Secret 32)",
    "",
    "POSTGRES_DB=indusmind",
    "POSTGRES_USER=indusmind",
    "POSTGRES_PASSWORD=$(New-Secret 24)",
    "POSTGRES_HOST=127.0.0.1",
    "POSTGRES_PORT=5433",
    "",
    "REDIS_URL=redis://127.0.0.1:6379/0",
    "",
    "UPLOAD_DIR=data/uploads",
    "ALLOWED_ORIGINS=http://localhost:5173,http://127.0.0.1:5173",
    "COOKIE_SECURE=false",
    "TESSERACT_CMD="
)
[System.IO.File]::WriteAllLines($EnvFile, $Lines)
Write-Host "Created .env with new secrets." -ForegroundColor Green
